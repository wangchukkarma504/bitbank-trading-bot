@dataclass
class OrderBookDepth:
    """Level 2 order book snapshot."""
    bids: List[Tuple[float, float]] = field(default_factory=list)  # (price, amount) sorted high to low
    asks: List[Tuple[float, float]] = field(default_factory=list)  # (price, amount) sorted low to high
    timestamp: Optional[int] = None


@dataclass
class PairConfig:
    """Configuration and precision attributes for supported pairs."""
    pair: str
    price_digits: int  # Price decimal precision (PD)
    amount_digits: int  # Order amount decimal precision (AD)
    min_amount: float = 0.0001
    maker_fee: float = -0.0002  # -0.02% maker rebate
    taker_fee: float = 0.0012   # +0.12% taker fee

    def format_price(self, price: float) -> str:
        """Format price string matching Bitbank precision."""
        if self.price_digits == 0:
            return str(int(round(price)))
        return f"{price:.{self.price_digits}f}"

    def format_amount(self, amount: float) -> str:
        """Format amount string matching Bitbank precision."""
        return f"{amount:.{self.amount_digits}f}"


